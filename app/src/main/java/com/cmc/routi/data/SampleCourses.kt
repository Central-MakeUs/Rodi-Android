private fun isJibunAddress(address: String): Boolean =
    Regex("(?:^|\\s)(?:[가-힣0-9]+(?:읍|면)\\s+)?[가-힣0-9]+(?:동|리|가)\\s+(?:산\\s*)?\\d+(?:-\\d+)?(?:\\s|$)").containsMatchIn(address)

private fun RoutiItem.toParkingCourse(): Course? {
    val latitude = lat ?: return null
    val longitude = lng ?: return null
    val parkingDetail = parking ?: return null
    val cityCode = when {
        address.startsWith("서울") -> "seoul"
        address.startsWith("부산") -> "busan"
        address.startsWith("대구") -> "daegu"
        address.startsWith("인천") -> "incheon"
        address.startsWith("광주") -> "gwangju"
        address.startsWith("대전") -> "daejeon"
        address.startsWith("울산") -> "ulsan"
        address.startsWith("세종") -> "sejong"
        address.startsWith("경기") -> "gyeonggi"
        address.startsWith("강원") -> "gangwon"
        address.startsWith("충청남도") -> "chungnam"
        address.startsWith("충청북도") -> "chungbuk"
        address.startsWith("전라남도") -> "jeonnam"
        address.startsWith("전라북도") -> "jeonbuk"
        address.startsWith("경상남도") -> "gyeongnam"
        address.startsWith("경상북도") -> "gyeongbuk"
        address.startsWith("제주") -> "jeju"
        else -> "parking"
    }
    val area = address.split(" ").getOrNull(1).orEmpty().ifBlank { "주차장" }
    val point = w(
        order = 0,
        type = S,
        name = name,
        lat = latitude,
        lng = longitude,
        address = address,
        jibunAddress = jibunAddress ?: address.takeIf(::isJibunAddress),
        category = "주차장",
    )
    return Course(
        id = id,
        itemType = RoutiItemType.PARKING,
        courseName = name,
        courseNickname = name,
        areaName = area,
        region = cityCode,
        difficulty = difficultyScore,
        trafficDensity = null,
        source = "공영주차장",
        sourceUrl = "",
        crawledAt = "",
        waypoints = listOf(
            point,
            point.copy(order = 1, type = E),
        ),
        features = CourseFeatures(parking = true),
        recommendation = rating,
        caution = parkingDetail.note.orEmpty(),
        bestTime = parkingDetail.operatingHours?.weekday.orEmpty(),
        enrichedDescription = summary,
        parkingDetail = parkingDetail,
    )
}

