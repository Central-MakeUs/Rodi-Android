private fun w(
    order: Int,
    type: WaypointType,
    name: String,
    lat: Double,
    lng: Double,
    address: String = "",
    jibunAddress: String? = null,
    category: String = "도로",
) = Waypoint(order, type, name, lat, lng, address, jibunAddress, category)

private val S = WaypointType.START
private val V = WaypointType.WAYPOINT
private val E = WaypointType.END

private fun Course.toServerItem(id: Int): RoutiItem {
    val start = startWaypoint
    return RoutiItem(
        id = id,
        type = RoutiItemType.COURSE,
        name = courseName,
        address = start.address,
        jibunAddress = start.jibunAddress,
        lat = start.lat,
        lng = start.lng,
        rating = recommendation,
        difficultyScore = difficulty,
        tags = tags.map { it.label },
        summary = enrichedDescription,
        cautions = caution.takeIf { it.isNotBlank() }?.let(::listOf).orEmpty(),
        recommendedTime = bestTime,
        distanceKm = null,
        estimatedMinutes = null,
        parking = null,
        course = RouteDetail(
            points = waypoints
                .sortedBy { it.order }
                .mapIndexed { index, point ->
                    RoutePoint(
                        id = index + 1,
                        sequence = index + 1,
                        role = point.type,
                        name = point.name,
                        address = point.address,
                        jibunAddress = point.jibunAddress,
                        lat = point.lat,
                        lng = point.lng,
                    )
                },
        ),
    )


}

private fun parking(
